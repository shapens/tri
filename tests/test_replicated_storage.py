ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tri import cli, pgstore  # noqa: E402
from tri.cli import SCHEMA_CATALOG  # noqa: E402
