DATABASE_URL = os.environ.get("TRI_TEST_DATABASE_URL") or os.environ.get("TRI_DATABASE_URL") or ""
S3_URL = os.environ.get("TRI_TEST_S3_URL", "")
STORAGE_ENV = ("TRI_DATABASE_URL", "TRI_DATABASE_SCHEMA", "TRI_OBJECT_STORE", "TRI_REMOTE", "TRI_ACTOR", "TRI_NODE_ID")


class TranslationTests(unittest.TestCase):
    def test_parameters_become_numbered_outside_string_literals(self) -> None:
        self.assertEqual(pgstore.translate("SELECT * FROM t WHERE a = ? AND b = '?' AND c = ?"), "SELECT * FROM t WHERE a = $1 AND b = '?' AND c = $2")

    def test_insert_or_ignore_becomes_on_conflict_do_nothing(self) -> None:
        self.assertEqual(pgstore.translate("INSERT OR IGNORE INTO t (a) VALUES (?)"), "INSERT INTO t (a) VALUES ($1) ON CONFLICT DO NOTHING")

    def test_sqlite_only_forms_are_rewritten(self) -> None:
        self.assertIn("GREATEST(cursor, $1)", pgstore.translate("UPDATE m SET cursor = MAX(cursor, ?) WHERE id = ?"))
        self.assertIn("CAST($1 AS TEXT) IS NULL", pgstore.translate("SELECT * FROM j WHERE (? IS NULL OR status = ?)"))
        self.assertIn("IN (SELECT NULL WHERE FALSE)", pgstore.translate("SELECT * FROM t WHERE id NOT IN ()"))

    def test_tables_gain_an_ordered_rowid_and_wider_types(self) -> None:
        ddl = pgstore.translate_ddl("CREATE TABLE IF NOT EXISTS t (id TEXT PRIMARY KEY, n INTEGER NOT NULL, x REAL, note TEXT DEFAULT 'INTEGER')")
        self.assertIn("rowid BIGINT GENERATED BY DEFAULT AS IDENTITY", ddl)
        self.assertIn("n BIGINT NOT NULL", ddl)
        self.assertIn("x DOUBLE PRECISION", ddl)
        self.assertIn("DEFAULT 'INTEGER'", ddl)  # literals are left alone

    def test_errors_keep_sqlite_exception_types(self) -> None:
        from tri.pgwire import PgError

        self.assertIsInstance(pgstore.translate_error(PgError({"C": "23505", "M": "duplicate"})), sqlite3.IntegrityError)
        self.assertIsInstance(pgstore.translate_error(PgError({"C": "42P01", "M": "missing"})), sqlite3.OperationalError)


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


@unittest.skipUnless(DATABASE_URL, "set TRI_TEST_DATABASE_URL to a PostgreSQL server to run multi-node tests")
class MultiNodeTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory(prefix="tri-replicated-")
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.schema = f"tri_test_{uuid.uuid4().hex[:12]}"
        self.addCleanup(self.drop_schema)
        self.objects = f"file://{(self.root / 'objects').as_posix()}"
        repo = self.root / "repo"
        (repo / "src").mkdir(parents=True)
        (repo / "src" / "app.py").write_bytes(b"print('v1')\n")
        (repo / "README.md").write_bytes(b"readme\n")
        self.repo = repo
        clean = {key: value for key, value in os.environ.items() if key not in STORAGE_ENV}
        patcher = mock.patch.dict(os.environ, clean, clear=True)
        patcher.start()
        self.addCleanup(patcher.stop)
        os.environ["TRI_AUTO_REAP"] = "0"

    def drop_schema(self) -> None:
        pgstore.close_pool()
        wire = Wire(DATABASE_URL)
        try:
            wire.simple(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')
        finally:
            wire.close()

    def node_env(self, name: str) -> dict[str, str]:
        return {
            "TRI_HOME": str(self.root / name),
            "TRI_DATABASE_URL": DATABASE_URL,
            "TRI_DATABASE_SCHEMA": self.schema,
            "TRI_OBJECT_STORE": self.objects,
            "TRI_NODE_ID": name,
            "TRI_AUTO_REAP": "0",
        }

    def tri(self, node: str | dict[str, str], *argv: str, ok: bool = True) -> dict:
        env = self.node_env(node) if isinstance(node, str) else node
        with mock.patch.dict(os.environ, env):
            output, _ = cli.execute_argv(list(argv))
        self.assertEqual(output["ok"], ok, output)
        for diagnostic in output["diagnostics"]:
            self.assertIn(diagnostic["code"], SCHEMA_CATALOG["tri.diagnostic"]["codes"])
        return output

    def serve(self, node: str) -> tuple[subprocess.Popen, str]:
        port = free_port()
        env = {**os.environ, **self.node_env(node)}
        proc = subprocess.Popen([sys.executable, "-m", "tri", "serve", "--port", str(port), "--quiet"], cwd=ROOT, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

        def stop() -> None:
            if proc.poll() is None:
                proc.terminate()
                try:
                    proc.communicate(timeout=5)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.communicate(timeout=5)

        self.addCleanup(stop)
        url = f"http://127.0.0.1:{port}"
        deadline = time.time() + 20
        while time.time() < deadline:
            try:
                with request.urlopen(f"{url}/v0/health", timeout=2) as response:
                    if response.status == 200:
                        return proc, url
            except (URLError, ConnectionError, TimeoutError):
                time.sleep(0.05)
        stop()
        self.fail(f"node {node} did not start: {proc.stderr.read().decode() if proc.stderr else ''}")

    def post(self, url: str, argv: list[str]) -> dict:
        req = request.Request(f"{url}/v0/command", data=json.dumps({"argv": argv}).encode(), method="POST")
        req.add_header("Content-Type", "application/json")
        with request.urlopen(req, timeout=60) as response:
            return json.loads(response.read())

    def test_a_write_on_one_node_is_readable_on_another(self) -> None:
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        ws = self.tri("a", "workspace", "create", "app", "--from", "main")["data"]["id"]
        self.tri("a", "files", "write", ws, "src/app.py", "--text", "print('v2')\n")
        read = self.tri("b", "files", "read", ws, "src/app.py")["data"]
        self.assertEqual(read["text"], "print('v2')\n")  # node b had no local copy: fetched from shared storage
        self.assertTrue(any((self.root / "objects" / "blobs").iterdir()))
        status = self.tri("b", "storage", "status")["data"]
        self.assertEqual(status["metadata"]["backend"], "postgres")
        self.assertTrue(status["multi_node"])
        self.assertEqual(status["node_id"], "b")
        password = urlparse(DATABASE_URL).password
        if password:
            self.assertNotIn(password, json.dumps(status))

    def test_check_logs_written_on_one_node_are_readable_on_another(self) -> None:
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        ws = self.tri("a", "workspace", "create", "app", "--from", "main")["data"]["id"]
        check = self.tri("a", "run", ws, "--", sys.executable, "-c", "print('hello from node a')")["data"]
        read = self.tri("b", "artifacts", "read", check["logs"]["stdout"])["data"]
        self.assertIn("hello from node a", read.get("text") or "")

    def test_concurrent_writes_through_two_nodes_lose_nothing(self) -> None:
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        _, url_a = self.serve("a")
        _, url_b = self.serve("b")
        workspaces = [self.post(url_a if i % 2 else url_b, ["workspace", "create", "app", "--from", "main"])["data"]["id"] for i in range(4)]
        failures: list[dict] = []

        def writer(index: int) -> None:
            url = url_a if index % 2 else url_b
            for attempt in range(20):
                output = self.post(url, ["files", "write", workspaces[index % len(workspaces)], f"notes/{index}.txt", "--text", f"{index}\n"])
                if output["ok"]:
                    return
                if not output["diagnostics"][0].get("retryable"):
                    failures.append(output)
                    return
                time.sleep(0.05 * (attempt + 1))
            failures.append({"index": index, "gave_up": True})

        threads = [threading.Thread(target=writer, args=(i,)) for i in range(16)]
        for thread in threads:
            thread.start()
        for thread in threads:
            thread.join(timeout=120)
        self.assertEqual(failures, [])
        for index in range(16):
            ws = workspaces[index % len(workspaces)]
            self.assertEqual(self.post(url_a, ["files", "read", ws, f"notes/{index}.txt"])["data"]["text"], f"{index}\n")

    def test_clients_fail_over_when_a_node_goes_away(self) -> None:
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        proc_a, url_a = self.serve("a")
        _, url_b = self.serve("b")
        client = {"TRI_REMOTE": f"{url_a},{url_b}", "TRI_HOME": str(self.root / "client"), "TRI_CACHE_DIR": str(self.root / "client-cache")}
        ws = self.tri(client, "workspace", "create", "app", "--from", "main")["data"]["id"]
        proc_a.terminate()
        proc_a.communicate(timeout=10)
        self.tri(client, "files", "write", ws, "src/after.txt", "--text", "written after failover\n")
        self.assertEqual(self.tri(client, "files", "read", ws, "src/after.txt")["data"]["text"], "written after failover\n")

    def test_each_node_reaps_only_its_own_directories(self) -> None:
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        ws = self.tri("a", "workspace", "create", "app", "--from", "main")["data"]["id"]
        mounted = self.tri("a", "workspace", "mount", ws, str(self.root / "mnt"), "--ttl-seconds", "1")["data"]
        time.sleep(1.5)
        self.tri("b", "gc", "--reap")
        self.assertTrue((self.root / "mnt" / "src" / "app.py").exists(), "node b must not reap node a's mount")
        self.assertTrue(mounted)
        self.tri("a", "gc", "--reap")
        self.assertFalse((self.root / "mnt" / "src" / "app.py").exists())

    def test_sqlite_store_migrates_to_shared_storage(self) -> None:
        single = {"TRI_HOME": str(self.root / "single"), "TRI_AUTO_REAP": "0"}
        self.tri(single, "import", str(self.repo), "--name", "app", "--target", "main")
        ws = self.tri(single, "workspace", "create", "app", "--from", "main")["data"]["id"]
        self.tri(single, "files", "write", ws, "src/app.py", "--text", "migrated\n")
        value = self.root / "token.txt"
        value.write_bytes(b"s3cr3t")
        secret = self.tri(single, "secrets", "put", "app", "TOKEN", "--value-file", str(value))["data"]["id"]
        migrated = self.tri(single, "storage", "migrate", "--database", DATABASE_URL, "--schema", self.schema, "--objects", self.objects)["data"]
        self.assertGreater(migrated["tables"]["blobs"], 0)
        self.assertGreater(migrated["objects"]["blobs"], 0)
        self.assertEqual(self.tri("fresh-node", "files", "read", ws, "src/app.py")["data"]["text"], "migrated\n")
        self.assertEqual(migrated["objects"]["secrets"], 1)
        with mock.patch.dict(os.environ, self.node_env("fresh-node")):
            store = cli.Store()
            try:
                row = store.row("SELECT value_path FROM secret_refs WHERE id = ?", (secret,))
                self.assertFalse(Path(row["value_path"]).is_absolute())
                self.assertEqual(cli.home_file(row["value_path"]).read_bytes(), b"s3cr3t")
            finally:
                store.close()
        again = self.tri(single, "storage", "migrate", "--database", DATABASE_URL, "--schema", self.schema, ok=False)
        self.assertEqual(again["diagnostics"][0]["code"], "invalid_command")

    def test_backup_of_a_shared_store_is_a_single_node_home(self) -> None:
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        ws = self.tri("a", "workspace", "create", "app", "--from", "main")["data"]["id"]
        self.tri("a", "files", "write", ws, "src/app.py", "--text", "backed up\n")
        dest = self.root / "backup"
        self.tri("b", "backup", "create", str(dest))  # node b never cached the blob locally
        restored = {"TRI_HOME": str(dest), "TRI_AUTO_REAP": "0"}
        self.assertEqual(self.tri(restored, "files", "read", ws, "src/app.py")["data"]["text"], "backed up\n")
        verify = self.tri("b", "backup", "verify", str(dest), "--deep")["data"]
        self.assertTrue(verify["ok"], verify)

    @unittest.skipUnless(S3_URL, "set TRI_TEST_S3_URL, TRI_OBJECT_STORE_ENDPOINT and AWS credentials to run S3 tests")
    def test_nodes_share_content_through_s3(self) -> None:
        self.objects = f"{S3_URL.rstrip('/')}/{self.schema}"
        self.tri("a", "import", str(self.repo), "--name", "app", "--target", "main")
        ws = self.tri("a", "workspace", "create", "app", "--from", "main")["data"]["id"]
        self.tri("a", "files", "write", ws, "src/app.py", "--text", "via s3\n")
        self.assertEqual(self.tri("b", "files", "read", ws, "src/app.py")["data"]["text"], "via s3\n")
        self.assertEqual(self.tri("b", "storage", "status")["data"]["objects"]["kind"], "s3")

    def test_unreachable_database_is_a_retryable_diagnostic(self) -> None:
        env = {**self.node_env("a"), "TRI_DATABASE_URL": f"postgres://nobody@127.0.0.1:{free_port()}/none?sslmode=disable&connect_timeout=2"}
        output = self.tri(env, "projects", "list", ok=False)
        self.assertEqual(output["diagnostics"][0]["code"], "store_unavailable")
        self.assertTrue(output["diagnostics"][0]["retryable"])


@unittest.skipUnless(S3_URL, "set TRI_TEST_S3_URL, TRI_OBJECT_STORE_ENDPOINT and AWS credentials to run S3 tests")
class S3ObjectStoreTests(unittest.TestCase):
    def test_put_get_delete_round_trip(self) -> None:
        store = object_store_from_url(S3_URL)
        key = f"tests/{uuid.uuid4().hex}"
        self.assertIsNone(store.get(key))
        store.put(key, b"\x00binary\xff" * 100)
        self.assertEqual(store.get(key), b"\x00binary\xff" * 100)
        store.delete(key)
        self.assertIsNone(store.get(key))


